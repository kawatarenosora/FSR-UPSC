<#
.SYNOPSIS
Build the unified fsr-upsc-agent.jar against the installed game revision.
.DESCRIPTION
Compiles src/fsrupsc with javac (JDK 25+) against <game>/projectzomboid.jar,
verifies zombie/GitVersion REVISION and drops the jar into 42/media/java -
the single jar (ZombieBuddy loads it via mod.info and the -javaagent launch
option points at the same file).

One jar, two loading modes:
- javaagent: -javaagent:<this jar> boots fsrupsc.FsrAgent.premain (load-time
  transform). Requires the manifest's Premain-Class and a bundled byte-buddy
  (the jar must be self-contained; no ZombieBuddy present to resolve from).
- ZombieBuddy java mod: ZB reads mod.info (javaJarFile/javaPkgName) and runs
  fsrupsc.Main, which boots fsrupsc.ZbEntry in the system classloader and
  retransforms already-loaded classes via ZB's own instrumentation. ZB ignores
  the manifest's agent attributes, and at runtime byte-buddy resolves from
  ZB's jar (classpath-first), so the bundled copy is only a fallback there.
- Both at once is safe: FsrAgent.premain and ZbEntry set/check the
  "fsrupsc.armed" system property, and ZbEntry additionally skips when
  -javaagent is visible in the JVM input arguments.

- One jar, curated revision whitelist: the primary target revision is
  generated as fsrupsc/BuildRev.java (a compile-time constant; jar
  resources are NOT readable under ZombieBuddy's transformed-jar loader)
  and also written to fsrupsc/build-info.properties for external loaders
  (PZ JAM Launcher). The runtime gate accepts every revision listed in
  fsrupsc/AgentRev.SUPPORTED (a source constant): before adding an entry,
  re-verify the hook targets against that game build's bytecode (javap the
  hook classes; an extracted game tree works as the offline classpath).
  mod.info's versionMin/versionMax gates the mod list; the hash gate
  remains hotfix insurance for unlisted builds (stock, safe side).
#>
param(
  [string]$GameDir = "E:\Program Files (x86)\Steam\steamapps\common\ProjectZomboid",
  [string]$Revision = ""                # defaults to the installed game's revision
)
$ErrorActionPreference = 'Stop'
$Jar = Join-Path $GameDir 'projectzomboid.jar'
if (-not (Test-Path -LiteralPath $Jar)) { throw "no projectzomboid.jar in $GameDir" }
# The revision hash is authoritative; it names the build inside the jar
# (build-info.properties, Target-Revision manifest attribute).
if (-not $Revision) {
  Add-Type -AssemblyName System.IO.Compression.FileSystem
  $z = [System.IO.Compression.ZipFile]::OpenRead($Jar)
  try {
    $e = $z.GetEntry('zombie/GitVersion.class')
    if (-not $e) { throw 'no zombie/GitVersion.class in jar' }
    $s = $e.Open(); $ms = New-Object System.IO.MemoryStream; $s.CopyTo($ms); $s.Dispose()
    $txt = [System.Text.Encoding]::ASCII.GetString($ms.ToArray())
  } finally { $z.Dispose() }
  $m = [regex]::Match($txt, '\b[0-9a-f]{10}\b')
  if (-not $m.Success) { throw "could not read game revision (pass -Revision)" }
  $Revision = $m.Value
}
# Locate a JDK 25+ (javac/jar), PATH first, then common install roots.
function Resolve-JdkTool([string]$tool) {
  $cmd = Get-Command $tool -ErrorAction SilentlyContinue
  if ($cmd) { return $cmd.Source }
  foreach ($root in @('C:\Program Files\Java', 'C:\Program Files\Eclipse Adoptium', 'C:\Program Files\Microsoft')) {
    if (Test-Path -LiteralPath $root) {
      $hit = Get-ChildItem -LiteralPath $root -Recurse -Filter "$tool.exe" -ErrorAction SilentlyContinue |
             Sort-Object FullName -Descending | Select-Object -First 1
      if ($hit) { return $hit.FullName }
    }
  }
  throw "$tool not found (need JDK 25+ on PATH or under C:\Program Files\Java)"
}
$Javac = Resolve-JdkTool 'javac'
$JarTool = Resolve-JdkTool 'jar'
$Root = Split-Path -Parent $PSScriptRoot
$Out = Join-Path $Root 'build\agent-classes'
$AgentJar = Join-Path $Root '42\media\java\fsr-upsc-agent.jar'
# Generate fsrupsc/BuildRev.java: the revision as a compile-time constant.
# A class constant is the only revision form that survives every loading
# context: ZombieBuddy's transformed-jar loader does not serve mod jar
# resources (BU's ZB edition prints "unversioned" for the same reason),
# while javac inlines constants into the classes that read them.
$GenDir = Join-Path $Root 'build\agent-gen\fsrupsc'
New-Item -ItemType Directory -Force -Path $GenDir | Out-Null
$Gen = @"
package fsrupsc;

/** Generated by scripts/build-agent.ps1 for revision $Revision. Do not edit. */
final class BuildRev {
    static final String REVISION = "$Revision";
    private BuildRev() {}
}
"@
[IO.File]::WriteAllText((Join-Path $GenDir 'BuildRev.java'), $Gen, (New-Object Text.ASCIIEncoding))
Remove-Item -Recurse -Force $Out -ErrorAction SilentlyContinue
New-Item -ItemType Directory -Force -Path $Out | Out-Null
# Compile against the game jar + vendor byte-buddy (1.18.8). The same jar
# runs as a -javaagent (bundled copy used) and as a ZombieBuddy java mod
# (ZB's own 1.18.x copy wins on the classpath); the 1.18.x API subset here
# is what both contexts serve.
$BbDir = Join-Path $Root 'vendor\lib'
$Bb = @(Get-ChildItem -LiteralPath $BbDir -Filter 'byte-buddy*.jar' | ForEach-Object { $_.FullName })
if ($Bb.Count -eq 0) { throw "no byte-buddy jars in $BbDir" }
$Sources = @(Get-ChildItem -LiteralPath (Join-Path $Root 'src') -Recurse -Filter '*.java' | ForEach-Object { $_.FullName })
$Sources += Join-Path $GenDir 'BuildRev.java'
& $Javac -encoding UTF-8 -cp ($Jar + ';' + ($Bb -join ';')) -d $Out $Sources
if ($LASTEXITCODE -ne 0) { throw 'javac failed' }
# Revision check against the game on disk; cross-builds (e.g. rebuilding the
# 42.21 jar after the disk moved to 42.22) are allowed with a warning. Safe:
# the target revision goes into build-info.properties and AgentRev refuses to
# arm on a mismatched game.
Add-Type -AssemblyName System.IO.Compression.FileSystem
$z = [System.IO.Compression.ZipFile]::OpenRead($Jar)
try {
  $e = $z.GetEntry('zombie/GitVersion.class')
  if (-not $e) { throw 'no zombie/GitVersion.class in jar' }
  $s = $e.Open(); $ms = New-Object System.IO.MemoryStream; $s.CopyTo($ms); $s.Dispose()
  $txt = [System.Text.Encoding]::ASCII.GetString($ms.ToArray())
} finally { $z.Dispose() }
$m = [regex]::Match($txt, '\b[0-9a-f]{10}\b')
if (-not $m.Success) { throw 'could not read game revision' }
if ($m.Value -ne $Revision) {
  Write-Warning "game is $($m.Value), building -Revision $Revision (cross-build)"
}
# fsrupsc/build-info.properties: unchanged entry for external loaders (PZ JAM
# Launcher greps it); the agent itself reads the BuildRev constant instead.
Set-Content -LiteralPath (Join-Path $Out 'fsrupsc\build-info.properties') `
  -Value "revision=$Revision" -Encoding ASCII
# Unpack byte-buddy into the classes dir so the agent jar is self-contained
# for the -javaagent mode (no ZombieBuddy present to resolve byte-buddy from).
# In the ZombieBuddy mode ZB's jar sits earlier on the classpath, so its own
# copy (1.18.x) keeps winning and this bundled copy stays a harmless fallback.
Push-Location -LiteralPath $Out
try {
  foreach ($b in $Bb) {
    & $JarTool --extract --file $b
    if ($LASTEXITCODE -ne 0) { throw "jar extract failed: $b" }
  }
} finally {
  Pop-Location
}
# Premain-Class makes the same jar bootable via -javaagent (the JVM aborts at
# startup without it). ZombieBuddy loads the jar as a plain java mod and
# ignores every agent manifest attribute, so both modes share one build.
# Can-Retransform/Can-Redefine keep late attaches and retransform passes
# possible in any loading context.
$Manifest = Join-Path ([IO.Path]::GetTempPath()) 'fsr-upsc-manifest.txt'
@(
  'Manifest-Version: 1.0',
  'Premain-Class: fsrupsc.FsrAgent',
  'Can-Redefine-Classes: true',
  'Can-Retransform-Classes: true',
  'Implementation-Title: fsr-upsc-agent',
  "Implementation-Version: $Revision",
  "Target-Revision: $Revision",
  ''
) | Set-Content -LiteralPath $Manifest -Encoding ASCII
if (Test-Path -LiteralPath $AgentJar) { Remove-Item -LiteralPath $AgentJar -Force }
& $JarTool --create --file $AgentJar --manifest $Manifest -C $Out .
Remove-Item -LiteralPath $Manifest -Force -ErrorAction SilentlyContinue
# Keep the Workshop staging copy in sync when present: mirror the whole 42\
# tree (mod.info, media), so a rebuild also ships lua / mod.info changes,
# not just the jar, and files removed from the repo (e.g. the retired
# agent\<build> folders) disappear from staging too. The old WIP copy under
# Zomboid\mods\FSR-UPSC is retired - the Workshop staging folder is the
# single deploy target now.
$Ws42 = Join-Path $env:USERPROFILE "Zomboid\Workshop\FSR-UPSC\Contents\mods\FSR-UPSC\42"
if (Test-Path -LiteralPath $Ws42) {
  robocopy (Join-Path $Root '42') $Ws42 /MIR /NJH /NJS /NFL /NDL /NP | Out-Null
  $rc = $LASTEXITCODE
  if ($rc -ge 8) { throw "robocopy to staging failed (exit $rc)" }
  Write-Output "synced $Ws42"
} else {
  Write-Output "note: Workshop staging copy absent ($Ws42), skipped sync"
}
Write-Output "built $AgentJar for game revision $Revision (byte-buddy bundled; javaagent + ZombieBuddy in one jar)"

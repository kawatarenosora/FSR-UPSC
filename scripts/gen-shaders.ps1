<#
.SYNOPSIS
Generate src/fsrupsc/Fsr2Shaders.java from 42/media/shaders/fsr2/*.glsl.
.DESCRIPTION
Embeds the AMD FidelityFX FSR2 compute shaders as Java string constants so
the agent jar stays self-contained (same practice as FSR1: Resolve.java
embeds fsr_easu/rcas and media/shaders mirrors them). Edit the .glsl files
and re-run this script; never edit Fsr2Shaders.java by hand.
#>
$ErrorActionPreference = 'Stop'
$Root = Split-Path -Parent $PSScriptRoot
$Dir = Join-Path $Root '42\media\shaders\fsr2'
$Out = Join-Path $Root 'src\fsrupsc\Fsr2Shaders.java'

$names = [ordered]@{
  'ACCUMULATE_CS.glsl'   = 'ACCUMULATE'
  'AUTO_REACTIVE_CS.glsl' = 'AUTO_REACTIVE'
  'DEPTH_CLIP_CS.glsl'   = 'DEPTH_CLIP'
  'DEPTH_PROXY_CS.glsl'  = 'DEPTH_PROXY'
  'LOCK_CS.glsl'         = 'LOCK'
  'MV_GEN_CS.glsl'       = 'MV_GEN'
  'MV_OVERRIDE_CS.glsl'  = 'MV_OVERRIDE'
  'RCAS_CS.glsl'         = 'RCAS'
  'RECONSTRUCT_CS.glsl'  = 'RECONSTRUCT'
}

$names3 = [ordered]@{
  'ACCUMULATE_CS.glsl'    = 'ACCUMULATE'
  'DEPTH_CLIP_CS.glsl'    = 'DEPTH_CLIP'
  'LOCK_CS.glsl'          = 'LOCK'
  'MV_GEN_CS.glsl'        = 'MV_GEN'
  'RCAS_CS.glsl'          = 'RCAS'
  'RECONSTRUCT_CS.glsl'   = 'RECONSTRUCT'
  'SHADING_CHANGE_CS.glsl' = 'SHADING_CHANGE'
}

function Write-ShadersClass([System.Text.StringBuilder]$sb, [string]$dir,
        [System.Collections.IDictionary]$table, [string]$className, [string]$outPath) {
  [void]$sb.AppendLine('package fsrupsc;')
  [void]$sb.AppendLine()
  [void]$sb.AppendLine('/**')
  [void]$sb.AppendLine(" * Embedded AMD FidelityFX compute shader sources (GL 4.3) for $className.")
  [void]$sb.AppendLine(' * GENERATED by scripts/gen-shaders.ps1 from the media/shaders mirror --')
  [void]$sb.AppendLine(' * do not edit by hand; edit the .glsl mirrors and regenerate.')
  [void]$sb.AppendLine(' * Provenance and license note: the NOTICE-*.txt next to the mirror.')
  [void]$sb.AppendLine(' */')
  [void]$sb.AppendLine("public final class $className {")
  foreach ($k in $table.Keys) {
    $p = Join-Path $dir $k
    if (-not (Test-Path -LiteralPath $p)) { throw "missing shader file: $p" }
    $lines = [IO.File]::ReadAllLines($p, [Text.Encoding]::UTF8)
    [void]$sb.AppendLine()
    [void]$sb.AppendLine("    /** mirror of $([IO.Path]::GetFileName($dir))/$k */")
    [void]$sb.AppendLine("    public static final String $($table[$k]) =")
    for ($i = 0; $i -lt $lines.Count; $i++) {
      $line = $lines[$i] -replace '\\', '\\\\' -replace '"', '\"'
      $nl = if ($i -lt $lines.Count - 1) { '\n' } else { '' }
      $op = if ($i -eq 0) { '' } else { '+ ' }
      [void]$sb.Append("        $op`"$line$nl`"")
      if ($i -lt $lines.Count - 1) { [void]$sb.AppendLine() } else { [void]$sb.AppendLine(';') }
    }
  }
  [void]$sb.AppendLine()
  [void]$sb.AppendLine("    private $className() {}")
  [void]$sb.AppendLine('}')
  [IO.File]::WriteAllText($outPath, $sb.ToString(), (New-Object Text.UTF8Encoding $false))
  "generated $outPath"
}

$sb2 = New-Object System.Text.StringBuilder
Write-ShadersClass $sb2 $Dir $names 'Fsr2Shaders' $Out

$Dir3 = Join-Path $Root '42\media\shaders\fsr3'
$Out3 = Join-Path $Root 'src\fsrupsc\Fsr3Shaders.java'
$sb3 = New-Object System.Text.StringBuilder
Write-ShadersClass $sb3 $Dir3 $names3 'Fsr3Shaders' $Out3
